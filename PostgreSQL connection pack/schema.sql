-- [SQL INTEGRATION] PostgreSQL 10+ schema. Run once against your database:
--   psql "$DATABASE_URL" -f schema.sql
CREATE TABLE users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(60)  NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  role          VARCHAR(10)  NOT NULL CHECK (role IN ('customer','staff','admin')),
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE devices (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(100) NOT NULL,
  type         VARCHAR(10)  NOT NULL CHECK (type IN ('pump','level')),
  region       VARCHAR(100),
  status       VARCHAR(20)  DEFAULT 'unknown',
  level_pct    NUMERIC(5,2),
  pump_state   VARCHAR(10),
  config       TEXT,
  api_key_hash VARCHAR(64)  NOT NULL,
  last_seen    TIMESTAMPTZ
);

CREATE TABLE metrics (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id   INTEGER     NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
  metric      VARCHAR(40) NOT NULL,
  value       NUMERIC,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX metrics_dev_time ON metrics (device_id, recorded_at);

CREATE TABLE files (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filename    VARCHAR(200) NOT NULL,
  stored_name VARCHAR(100) NOT NULL,
  uploaded_by VARCHAR(60),
  uploaded_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- [SQL INTEGRATION] Tag-based device access.
-- A customer can see a device only if the device and the customer share a tag.
-- Staff and admins always see every device.
CREATE TABLE tags (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(40) NOT NULL UNIQUE
);
CREATE TABLE device_tags (
  device_id INTEGER NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
  tag_id    INTEGER NOT NULL REFERENCES tags(id)    ON DELETE CASCADE,
  PRIMARY KEY (device_id, tag_id)
);
CREATE TABLE user_tags (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  tag_id  INTEGER NOT NULL REFERENCES tags(id)  ON DELETE CASCADE,
  PRIMARY KEY (user_id, tag_id)
);
