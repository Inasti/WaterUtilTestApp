-- [SQL INTEGRATION] Oracle 12c+ schema. Run once as your application user.
CREATE TABLE USERS (
  ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USERNAME      VARCHAR2(60)  NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR2(100) NOT NULL,
  ROLE          VARCHAR2(10)  NOT NULL CHECK (ROLE IN ('customer','staff','admin')),
  CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE DEVICES (
  ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME          VARCHAR2(100) NOT NULL,
  TYPE          VARCHAR2(10)  NOT NULL CHECK (TYPE IN ('pump','level')),
  REGION        VARCHAR2(100),
  STATUS        VARCHAR2(20)  DEFAULT 'unknown',
  LEVEL_PCT     NUMBER(5,2),
  PUMP_STATE    VARCHAR2(10),
  CONFIG        CLOB,
  API_KEY_HASH  VARCHAR2(64) NOT NULL,
  LAST_SEEN     TIMESTAMP
);

CREATE TABLE METRICS (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  DEVICE_ID   NUMBER NOT NULL REFERENCES DEVICES(ID) ON DELETE CASCADE,
  METRIC      VARCHAR2(40) NOT NULL,
  VALUE       NUMBER,
  RECORDED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);
CREATE INDEX METRICS_DEV_TIME ON METRICS (DEVICE_ID, RECORDED_AT);

CREATE TABLE FILES (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FILENAME    VARCHAR2(200) NOT NULL,
  STORED_NAME VARCHAR2(100) NOT NULL,
  UPLOADED_BY VARCHAR2(60),
  UPLOADED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- [SQL INTEGRATION] Tag-based device access (added in v2).
-- A customer can see a device only if the device and the customer share a tag.
-- Staff and admins always see every device.
CREATE TABLE TAGS (
  ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR2(40) NOT NULL UNIQUE
);
CREATE TABLE DEVICE_TAGS (
  DEVICE_ID NUMBER NOT NULL REFERENCES DEVICES(ID) ON DELETE CASCADE,
  TAG_ID    NUMBER NOT NULL REFERENCES TAGS(ID)    ON DELETE CASCADE,
  PRIMARY KEY (DEVICE_ID, TAG_ID)
);
CREATE TABLE USER_TAGS (
  USER_ID NUMBER NOT NULL REFERENCES USERS(ID) ON DELETE CASCADE,
  TAG_ID  NUMBER NOT NULL REFERENCES TAGS(ID)  ON DELETE CASCADE,
  PRIMARY KEY (USER_ID, TAG_ID)
);
